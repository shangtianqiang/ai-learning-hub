/* 每个分类的课程与课时数 */
CATEGORIES.forEach(c => {
  const cs = COURSES.filter(x => x.cat === c.id);
  c.courses = cs.length;
  c.lessons = cs.reduce((a, x) => a + x.chapters.reduce((b, ch) => b + ch.lessons.length, 0), 0);
});

/* 课程课时数与总时长 */
COURSES.forEach((c, i) => {
  c.no = 'C0' + (i + 1);
  c.lessonCount = c.chapters.reduce((a, ch) => a + ch.lessons.length, 0);
  c.mins = c.chapters.reduce((a, ch) => a + ch.lessons.reduce((b, l) => b + l.mins, 0), 0);
  c.hours = (c.mins / 60).toFixed(1);
});

/* 课程内课时的前后关系 */
function getCourseLessons(slug) {
  return ALL_LESSONS.filter(l => l.courseSlug === slug);
}
function getAdjacent(slug, lessonId) {
  const list = getCourseLessons(slug);
  const i = list.findIndex(l => l.id === lessonId);
  return { prev: i > 0 ? list[i - 1] : null, next: i >= 0 && i < list.length - 1 ? list[i + 1] : null };
}

